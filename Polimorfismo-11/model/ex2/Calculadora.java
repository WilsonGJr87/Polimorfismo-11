package model.ex2;

public class Calculadora {
    
    public void somar(int a, int b) {
        System.out.println(a + " + " + b + " = " + (a + b));
    }
    
    public void somar(int a, int b, int c) {
        System.out.println(a + " + " + b + " + " + c + " = " + (a + b + c));
    }
    
    public void somar(double a, double b) {
        System.out.println(a + " + " + b + " = " + (a + b));
    }

}